"""Build the labelled validation fixtures in tests/fixtures/.

Sources (all redistributable; see docs/ATTRIBUTION.md):
  - TripoSR example images (MIT, VAST-AI-Research/TripoSR, examples/)
    pass the cloned repo with --triposr /path/to/TripoSR
  - scikit-image sample data (astronaut: NASA public domain; chelsea: CC0;
    rocket: NASA public domain; coffee: CC0)
  - derived/synthetic images generated by this script from the above

Usage: python -I scripts/make_fixtures.py --triposr /tmp/TripoSR
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np
import skimage.data as skd
from PIL import Image, ImageEnhance, ImageFilter

OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures"

ACCEPT = "accept"


def rgb(im: Image.Image) -> Image.Image:
    if im.mode == "RGBA":
        bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
        return Image.alpha_composite(bg, im).convert("RGB")
    return im.convert("RGB")


def on_canvas(items: list[tuple[Image.Image, tuple[int, int]]], size=(1400, 900), color=(245, 245, 243)) -> Image.Image:
    canvas = Image.new("RGB", size, color)
    for im, pos in items:
        im = im.convert("RGBA") if im.mode != "RGBA" else im
        canvas.paste(im, pos, im)
    return canvas


def cutout(im: Image.Image, bg_tol: int = 18) -> Image.Image:
    """Make the flat background of a product shot transparent (for compositing)."""
    a = np.asarray(im.convert("RGB")).astype(np.int16)
    ref = np.median(np.concatenate([a[0], a[-1], a[:, 0], a[:, -1]]), axis=0)
    mask = (np.abs(a - ref).sum(axis=2) > bg_tol).astype(np.uint8) * 255
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((7, 7), np.uint8))
    out = im.convert("RGBA")
    out.putalpha(Image.fromarray(mask))
    return out.crop(out.getbbox())


def synth_vase(size=1200) -> Image.Image:
    """A shaded vase silhouette rendered procedurally (no third-party content)."""
    img = np.full((size, size, 3), 246, np.uint8)
    cx = size // 2
    top, bottom = int(size * 0.15), int(size * 0.86)
    for y in range(top, bottom):
        t = (y - top) / (bottom - top)
        r = size * (0.08 + 0.17 * np.sin(np.pi * (0.15 + 0.85 * t)) ** 1.5 + (0.03 if t < 0.05 else 0))
        x0, x1 = int(cx - r), int(cx + r)
        xs = np.arange(x0, x1)
        shade = 0.55 + 0.45 * np.cos((xs - cx) / max(r, 1) * np.pi / 2 - 0.5)
        base = np.array([176, 92, 62])  # terracotta
        img[y, x0:x1] = np.clip(base[None] * shade[:, None] + 40 * (1 - t), 0, 255).astype(np.uint8)
    # subtle glaze bands for texture
    for k in range(6):
        y = int(top + (bottom - top) * (0.3 + 0.08 * k))
        img[y : y + 3] = np.where(img[y : y + 3] < 240, img[y : y + 3] * 0.85, img[y : y + 3]).astype(np.uint8)
    cv2.ellipse(img, (cx, bottom + 8), (int(size * 0.17), 14), 0, 0, 360, (215, 215, 212), -1)
    return Image.fromarray(img)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--triposr", required=True, type=Path, help="path to a clone of VAST-AI-Research/TripoSR")
    args = ap.parse_args()
    ex = args.triposr / "examples"
    OUT.mkdir(parents=True, exist_ok=True)
    manifest: list[dict] = []

    def save(name: str, im: Image.Image, expected: str, source: str, license_: str, note: str = "", fmt: str = "PNG"):
        path = OUT / name
        im.save(path, fmt, quality=92) if fmt == "JPEG" else im.save(path, fmt)
        manifest.append({"file": name, "expected": expected, "source": source, "license": license_, "note": note})

    tri = "VAST-AI-Research/TripoSR examples/"
    teapot = Image.open(ex / "teapot.png").convert("RGB")
    # ---- should be accepted
    save("accept_teapot_ceramic.png", teapot, ACCEPT, tri + "teapot.png", "MIT")
    save("accept_vase_synthetic.png", synth_vase(), ACCEPT, "generated by make_fixtures.py", "MIT (project)")
    save(
        "accept_sculpture_marble.png",
        Image.open(ex / "marble.png").convert("RGB"),
        ACCEPT,
        tri + "marble.png",
        "MIT",
        "Statue of a cherub: a sculpture, not a person.",
    )
    save(
        "accept_ornament_polyfox.png",
        Image.open(ex / "poly_fox.png").convert("RGB"),
        ACCEPT,
        tri + "poly_fox.png",
        "MIT",
        "Low-poly decorative figurine.",
    )

    # ---- should be rejected (expected primary code)
    save("reject_animal_horse.png", Image.open(ex / "horse.png"), "ANIMAL_DETECTED", tri + "horse.png", "MIT")
    save("reject_animal_flamingo.png", Image.open(ex / "flamingo.png"), "ANIMAL_DETECTED", tri + "flamingo.png", "MIT")
    chelsea = Image.fromarray(skd.chelsea()).resize((902, 600), Image.Resampling.LANCZOS)
    save("reject_animal_cat.jpg", chelsea, "ANIMAL_DETECTED", "scikit-image data.chelsea (upscaled 2x)", "CC0", fmt="JPEG")
    save(
        "reject_human_police.png",
        Image.open(ex / "police_woman.png"),
        "HUMAN_DETECTED",
        tri + "police_woman.png",
        "MIT",
        "Rendered human figure.",
    )
    save(
        "reject_human_astronaut.png",
        Image.fromarray(skd.astronaut()),
        "HUMAN_DETECTED",
        "scikit-image data.astronaut",
        "Public domain (NASA)",
    )
    save("reject_category_hamburger.png", Image.open(ex / "hamburger.png"), "UNSUPPORTED_CATEGORY", tri + "hamburger.png", "MIT")
    save(
        "reject_category_chair.png",
        Image.open(ex / "chair.png"),
        "UNSUPPORTED_CATEGORY",
        tri + "chair.png",
        "MIT",
        "Furniture is not an MVP category.",
    )

    tp = cutout(teapot).resize((560, 560 * cutout(teapot).height // cutout(teapot).width))
    save(
        "reject_two_products.png",
        on_canvas([(tp, (80, 200)), (tp, (760, 200))]),
        "MULTIPLE_PRODUCTS",
        "derived from " + tri + "teapot.png",
        "MIT",
        "Two copies of the teapot side by side.",
    )
    tiles = [rgb(Image.open(ex / f)).resize((600, 600)) for f in ("teapot.png", "chair.png", "robot.png", "hamburger.png")]
    collage = Image.new("RGB", (1212, 1212), (255, 255, 255))
    for k, t in enumerate(tiles):
        collage.paste(t, (6 + (k % 2) * 606, 6 + (k // 2) * 606))
    save("reject_collage.jpg", collage, "MULTIPLE_PRODUCTS", "derived collage of TripoSR examples", "MIT", fmt="JPEG")

    save("reject_blurry.png", teapot.filter(ImageFilter.GaussianBlur(9)), "TOO_BLURRY", "derived from teapot.png", "MIT")
    w, h = teapot.size
    save(
        "reject_cropped.png",
        teapot.crop((int(w * 0.30), int(h * 0.18), w, int(h * 0.82))).resize((800, 784)),
        "PRODUCT_CROPPED",
        "derived from teapot.png",
        "MIT",
        "Left part of the product cut off.",
    )
    save("reject_low_resolution.png", teapot.resize((360, 360)), "LOW_RESOLUTION", "derived from teapot.png", "MIT")
    save("reject_dark.png", ImageEnhance.Brightness(teapot).enhance(0.12), "BAD_EXPOSURE", "derived from teapot.png", "MIT")

    cup = Image.fromarray(skd.coffee()).crop((150, 20, 470, 330))
    cup_cut = cup.resize((260, 252)).convert("RGBA")
    save(
        "reject_extra_object.png",
        on_canvas([(tp, (200, 180)), (cup_cut, (1000, 520))]),
        "OTHER_FOREGROUND_OBJECTS",
        "teapot.png + scikit-image data.coffee (CC0)",
        "MIT / CC0",
        "Teapot with a coffee cup beside it.",
    )
    astro = Image.fromarray(skd.astronaut()).resize((420, 420)).convert("RGBA")
    save(
        "reject_person_with_product.png",
        on_canvas([(tp, (120, 200)), (astro, (860, 300))]),
        "HUMAN_DETECTED",
        "teapot.png + scikit-image data.astronaut",
        "MIT / Public domain",
    )

    (OUT / "reject_fake_extension.png").write_bytes(b"<html>this is not an image</html>\n" * 50)
    manifest.append(
        {
            "file": "reject_fake_extension.png",
            "expected": "INVALID_FILE",
            "source": "generated text file",
            "license": "MIT (project)",
            "note": "HTML text saved with a .png name.",
        }
    )

    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(manifest)} fixtures to {OUT}")


if __name__ == "__main__":
    main()
